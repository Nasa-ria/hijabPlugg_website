/**
 * Prepares the site's self-hosted fonts (run by `npm run build`, or `npm run fonts`).
 *
 * Text fonts: copies only the Latin files of Montserrat / Bodoni Moda into resources/fonts/text
 * and makes a tiny file for the cedi sign (see step 5).
 *
 * Icons: builds a small Font Awesome icon font containing only the icons this site uses.
 *
 * The full Font Awesome download is ~300 KB of fonts; the site uses ~100 icons.
 * This script scans the Blade views, JS and PHP for "fa-…" class names, subsets the
 * solid / regular / brands fonts to those glyphs and writes:
 *   resources/fonts/fa/*.woff2      (tiny fonts, bundled by Vite)
 *   resources/css/icons.css         (Font Awesome CSS with only the used icons)
 *
 * Runs automatically before `npm run build`; run `npm run fonts` after adding an icon.
 * Icon names must appear literally in the source (e.g. 'fa-truck'), not built from strings.
 */
import { readFileSync, writeFileSync, mkdirSync, readdirSync, statSync } from 'node:fs';
import { join, extname } from 'node:path';
import subsetFont from 'subset-font';

const root = new URL('..', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1');
const fa = join(root, 'node_modules/@fortawesome/fontawesome-free');
const outFonts = join(root, 'resources/fonts/fa');
const outCss = join(root, 'resources/css/icons.css');

// 1. Find every fa-* class used in the project
const scanDirs = ['resources/views', 'resources/js', 'app', 'config'];
const scanExt = new Set(['.php', '.js', '.mjs']);
const used = new Set();
const walk = (dir) => {
    for (const name of readdirSync(dir)) {
        const path = join(dir, name);
        if (statSync(path).isDirectory()) walk(path);
        else if (scanExt.has(extname(name))) {
            for (const [, icon] of readFileSync(path, 'utf8').matchAll(/\bfa-([a-z0-9]+(?:-[a-z0-9]+)*)/g)) used.add(icon);
        }
    }
};
scanDirs.forEach((dir) => walk(join(root, dir)));

// 2. Map names (and aliases) to glyphs and the free fonts that contain them
const families = JSON.parse(readFileSync(join(fa, 'metadata/icon-families.json'), 'utf8'));
const byName = new Map();
for (const [name, icon] of Object.entries(families)) {
    const styles = (icon.familyStylesByLicense?.free ?? []).filter((s) => s.family === 'classic').map((s) => s.style);
    if (!styles.length) continue;
    const entry = { unicode: String.fromCodePoint(parseInt(icon.unicode, 16)), styles };
    byName.set(name, entry);
    for (const alias of icon.aliases?.names ?? []) byName.set(alias, entry);
}

const glyphs = { solid: new Set(), regular: new Set(), brands: new Set() };
const icons = new Set();
for (const name of used) {
    const entry = byName.get(name);
    if (!entry) continue; // utility classes such as fa-fw, fa-spin, fa-solid
    icons.add(name);
    entry.styles.forEach((style) => glyphs[style]?.add(entry.unicode));
}

// 3. Subset the fonts
mkdirSync(outFonts, { recursive: true });
const files = { solid: 'fa-solid-900', regular: 'fa-regular-400', brands: 'fa-brands-400' };
const sizes = {};
for (const [style, file] of Object.entries(files)) {
    const source = readFileSync(join(fa, 'webfonts', `${file}.ttf`));
    const text = [...glyphs[style]].join('') || ' ';
    const subset = await subsetFont(source, text, { targetFormat: 'woff2' });
    writeFileSync(join(outFonts, `${file}.woff2`), subset);
    sizes[file] = subset.length;
}

// 4. Font Awesome CSS with only the used icon rules and the subset fonts
let css = readFileSync(join(fa, 'css/all.min.css'), 'utf8');
css = css.replace(/\/\*![\s\S]*?\*\//, '');
// Drop every @font-face (incl. the v4/v5 compatibility ones) and add ours below
css = css.replace(/@font-face\{[^}]*\}/g, '');
// Icon rules look like ".fa-truck{--fa:"\f0d1"}" (aliases may share a rule)
css = css.replace(/([^{}]+)\{--fa:"[^"]*"\}/g, (rule, selectors) => {
    const keep = selectors.split(',').filter((s) => {
        const m = s.trim().match(/^\.fa-([a-z0-9-]+)$/);
        return !m || icons.has(m[1]);
    });
    return keep.length ? rule.replace(selectors, keep.join(',')) : '';
});

const face = (familyName, weight, file) =>
    `@font-face{font-family:"${familyName}";font-style:normal;font-weight:${weight};font-display:block;src:url(../fonts/fa/${file}.woff2) format("woff2")}`;

const header = `/* Generated by scripts/build-icons.mjs from Font Awesome Free ${JSON.parse(readFileSync(join(fa, 'package.json'), 'utf8')).version}
   (Icons: CC BY 4.0, Fonts: SIL OFL 1.1, Code: MIT - https://fontawesome.com/license/free).
   Contains only the ${icons.size} icons used by this site. Do not edit: run "npm run fonts". */\n`;

writeFileSync(outCss, header
    + face('Font Awesome 6 Free', 900, files.solid)
    + face('Font Awesome 6 Free', 400, files.regular)
    + face('Font Awesome 6 Brands', 400, files.brands)
    + css + '\n');

const missing = [...used].filter((n) => !byName.has(n) && !/^(fw|xs|sm|lg|xl|2xs|2xl|[1-9]x|10x|spin|spin-pulse|pulse|beat|fade|beat-fade|bounce|flip|shake|rotate-\d+|rotate-by|flip-horizontal|flip-vertical|flip-both|stack|stack-1x|stack-2x|inverse|border|pull-left|pull-right|ul|li|width-auto|solid|regular|brands|classic|sharp|duotone|light|thin)$/.test(n));
const kb = (b) => (b / 1024).toFixed(1) + ' KB';
console.log(`Icons: ${icons.size} used → ${Object.entries(sizes).map(([f, s]) => `${f} ${kb(s)}`).join(', ')}`);

// 5. Text fonts (referenced by resources/css/fonts.css)
//    Only the Latin files are shipped. The cedi sign ₵ lives in Montserrat's 70 KB "latin-ext"
//    file, which every price would otherwise trigger, so it gets its own ~4 KB file instead.
//    (Bodoni Moda has no ₵ glyph, so its latin-ext file is not needed at all.)
const outText = join(root, 'resources/fonts/text');
mkdirSync(outText, { recursive: true });
const montserrat = join(root, 'node_modules/@fontsource-variable/montserrat/files');
const bodoni = join(root, 'node_modules/@fontsource-variable/bodoni-moda/files');
const copies = {
    'montserrat-latin-wght.woff2': join(montserrat, 'montserrat-latin-wght-normal.woff2'),
    'bodoni-moda-latin-opsz.woff2': join(bodoni, 'bodoni-moda-latin-opsz-normal.woff2'),
    'bodoni-moda-latin-opsz-italic.woff2': join(bodoni, 'bodoni-moda-latin-opsz-italic.woff2'),
};
for (const [name, source] of Object.entries(copies)) {
    writeFileSync(join(outText, name), readFileSync(source));
}
const cedi = await subsetFont(readFileSync(join(montserrat, 'montserrat-latin-ext-wght-normal.woff2')), '₵', { targetFormat: 'woff2' });
writeFileSync(join(outText, 'montserrat-cedi-wght.woff2'), cedi);
console.log(`Text fonts: Montserrat ${kb(readFileSync(copies['montserrat-latin-wght.woff2']).length)} + cedi sign ${kb(cedi.length)}, Bodoni Moda ${kb(readFileSync(copies['bodoni-moda-latin-opsz.woff2']).length)}`);
if (missing.length) console.log(`Not Font Awesome icons (ignored): ${missing.join(', ')}`);
